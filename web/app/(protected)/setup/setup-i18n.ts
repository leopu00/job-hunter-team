export type SetupT = (key: keyof typeof T | string) => string;

/** Risolve una chiave semplice. */
export function t(key: keyof typeof T | string, locale: Locale): string {
  const entry = T[key as string];
  if (!entry) return key as string;
  return entry[locale] ?? entry.it;
}

/** Helper legato a una locale, per i componenti client. */
export function getSetupT(locale: Locale): SetupT {
  return (key) => t(key, locale);
}

