export const RUNTIME_TEXT: Record<Locale, RuntimeCopy> = { it, en, de, es, fr, hu, pt };

export function isRuntimeTextKey(value: string): value is RuntimeTextKey {
  return Object.prototype.hasOwnProperty.call(it, value);
}

/** The sentence of a `ui_*` key in `locale`; null for anything else. */
export function runtimeText(value: string, locale: Locale): string | null {
  return isRuntimeTextKey(value) ? RUNTIME_TEXT[locale][value] : null;
}
