export const STATE_TEXT: Record<Locale, StateCopy> = { it, en, de, es, fr, hu, pt };

/** The gate's texts in the app's language. */
export function stateText(): StateCopy {
  return STATE_TEXT[appLocale()];
}

export type StateFailureStage = keyof StateCopy["failure"];
export function failureText(stage: OnboardingRuntimeStage): string {
  const failures = stateText().failure;
  return stage in failures ? failures[stage as StateFailureStage] : failures.runtime;
}
